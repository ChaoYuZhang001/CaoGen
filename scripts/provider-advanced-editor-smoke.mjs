#!/usr/bin/env node
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (file) => readFileSync(path.join(root, file), 'utf8')
const editor = read('src/renderer/src/components/ProviderEditor.tsx')
const advanced = read('src/renderer/src/components/ProviderAdvancedConfigEditor.tsx')
const anthropic = read('src/renderer/src/components/ProviderAnthropicRuntimeSection.tsx')
const checks = []

check(editor.includes("import ProviderAdvancedConfigEditor from './ProviderAdvancedConfigEditor'"), 'Provider editor imports the structured editor')
check(editor.includes('availableModels={modelsText.split(/\\r?\\n/)'), 'structured editor receives the current discovered model list')
check(editor.includes('onChange={setAdvancedConfigText}'), 'structured and JSON views share the persisted text state')
check(editor.includes('provider-editor-section-nav') && editor.includes("[data-provider-model-catalog]"), 'long Provider configuration exposes direct section navigation')
check(editor.includes("[data-provider-reliability-config]") && editor.includes("t('providerEditorSectionReliability')"), 'Provider navigation links directly to reliability controls')
check(advanced.includes("useState<'structured' | 'json'>('structured')"), 'structured and JSON views are available')
check(advanced.includes("t('providerAddEndpoint')") && advanced.includes("t('providerRemoveEndpoint')"), 'endpoint profiles support localized add and remove controls')
check(advanced.includes("t('providerEndpointPriority')") && advanced.includes('priority: numberOrUndefined'), 'endpoint priority is editable in the visual editor')
check(advanced.includes('updatePricing') && advanced.includes('inputPerMillion') && advanced.includes('outputPerMillion'), 'model pricing is editable')
check(advanced.includes('fetchProviderPricingCatalog') && advanced.includes('mergeCatalogPricing'), 'models.dev pricing import is wired')
check(advanced.includes("source: 'user'") && advanced.includes('protectedUserPrices'), 'manual pricing is marked and protected')
check(advanced.includes('syncDiscoveredModelProfiles'), 'discovered models can be synchronized into profiles')
check(advanced.includes('aliases: splitList'), 'model aliases are editable')
check(advanced.includes('renameBinding') && advanced.includes('modelMap: linesToMap'), 'app bindings and model maps are editable')
check(advanced.includes("t('providerRequestOverrides')") && advanced.includes("t('providerBalanceQuery')") && advanced.includes("t('providerMetadata')"), 'request, balance, and metadata sections are localized and present')
check(advanced.includes('data-provider-billing-query')
  && advanced.includes("t('providerBillingQueryTitle')")
  && advanced.includes('DEFAULT_BILLING_QUERY'), 'official billing API has an enableable visual section')
check(advanced.includes('periodStart') && advanced.includes('periodEnd')
  && advanced.includes('unix-seconds') && advanced.includes('unix-ms')
  && advanced.includes('value="iso"'), 'billing period targets and formats are visually configurable')
check(advanced.includes('itemsPath') && advanced.includes('amountPath')
  && advanced.includes('currencyPath') && advanced.includes('setBillingResponse'),
  'billing response item, amount, currency, and scale mappings are editable')
check(advanced.includes('keyLabel') && advanced.includes('credentialMode')
  && advanced.includes('setBillingPeriodLocation'), 'billing credentials and nested period locations are editable')
check(advanced.includes('data-provider-runtime-config')
  && advanced.includes('reasoningEffort')
  && advanced.includes('maxOutputTokens')
  && advanced.includes('parallelToolCalls')
  && advanced.includes('storeResponses'), 'typed OpenAI and Codex runtime controls are present')
check(advanced.includes("import ProviderAnthropicRuntimeSection from './ProviderAnthropicRuntimeSection'")
  && anthropic.includes('data-provider-anthropic-runtime')
  && anthropic.includes('setThinkingMode')
  && anthropic.includes('budgetTokens')
  && anthropic.includes('promptCaching')
  && anthropic.includes("options={['automatic', 'system', 'tools', 'last-user']}")
  && anthropic.includes('topK'), 'typed Anthropic Thinking, Prompt Cache, and top K controls are present')
check(advanced.includes('data-provider-reliability-config')
  && advanced.includes('maxRetries')
  && advanced.includes('streamingFirstByteTimeoutSeconds')
  && advanced.includes('streamingIdleTimeoutSeconds')
  && advanced.includes('requestTimeoutSeconds'), 'Provider failover, retry, and timeout controls are present')
check(advanced.includes('data-provider-circuit-config')
  && advanced.includes('failureThreshold')
  && advanced.includes('successThreshold')
  && advanced.includes('errorRateThreshold')
  && advanced.includes('minRequests'), 'Provider circuit-breaker controls are present')
check(advanced.includes('min={0}') && advanced.includes('max={20}') && advanced.includes('max={3600}'), 'reliability controls expose runtime validation bounds')
check(advanced.includes('const next = parseDraft(value).draft') && advanced.includes('...(parsed as Record<string, unknown>)'), 'structured edits merge from the current JSON object')
check(!/encryptedToken|apiKey|accessToken|refreshToken/.test(`${advanced}\n${anthropic}`), 'advanced editor does not expose credential fields')

console.log(`provider advanced editor smoke ok: ${checks.length}/${checks.length} checks passed`)

function check(condition, message) {
  assert(condition, message)
  checks.push(message)
}
